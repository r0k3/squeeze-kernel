"""SqueezeKernel API and the cross-engine golden.

``golden/research_engine.npz`` was generated by the research engine
(experiments/v2/variants.py::v2_series in the paper's repository) on a
synthetic one-factor panel with late listings and MCAR missing values;
the library must reproduce its per-day one-step NLL path.
"""
from pathlib import Path

import numpy as np
import pytest

import squeeze_kernel
from squeeze_kernel import SqueezeKernel

GOLDEN = Path(__file__).parent / "golden" / "research_engine.npz"


def _make_spd(cov, eps=1e-8):
    cov = (cov + cov.T) * 0.5
    min_eig = float(np.linalg.eigvalsh(cov).min())
    if min_eig < eps:
        cov = cov + np.eye(cov.shape[0]) * (eps - min_eig)
    return cov


def _nll(cov, r):
    sign, logdet = np.linalg.slogdet(cov)
    if sign <= 0:
        return float("nan")
    return float(logdet + r @ np.linalg.solve(cov, r))


def test_public_class_matches_research_engine():
    """``SqueezeKernel()`` is the research engine's promoted row."""
    d = np.load(GOLDEN)
    X, es = d["X"], int(d["eval_start"][0])
    sk = SqueezeKernel(lam=0.996)
    out = []
    for t in range(X.shape[0] - 1):
        sk.update(X[t])
        if t >= es:
            rn = X[t + 1]
            out.append(_nll(_make_spd(sk.covariance()), rn) if np.isfinite(rn).all() else np.nan)
    nll, ref = np.asarray(out), d["nll_tyler"]
    assert (np.isfinite(nll) == np.isfinite(ref)).all()
    both = np.isfinite(nll)
    dmax = float(np.max(np.abs(nll[both] - ref[both])))
    assert dmax < 1e-8, f"max per-day NLL drift {dmax:.2e}"


def test_derived_ladder():
    sk = SqueezeKernel(lam=0.996)
    sk.update(np.zeros(5) + 0.01)
    assert abs(sk.half_life - 172.94) < 0.01
    np.testing.assert_allclose(sk._est._corr_lam, (0.996 ** 4, 0.996, 0.996 ** 0.25))
    s = np.sqrt((0.25, 1.0, 4.0))
    np.testing.assert_allclose(sk._est._corr_w, s / s.sum())


def test_asset_clocks_differentiate():
    # two independent blocks; shock only block A: A's clocks must run ahead of B's
    rng = np.random.default_rng(9)
    n = 12
    X = rng.standard_normal((224, n)) * 0.01
    X[:, :6] += np.outer(rng.standard_normal(224) * 0.01, np.ones(6))
    X[200:, :6] *= 6.0
    sk = SqueezeKernel()
    for r in X:
        sk.update(r)
    S_a = sk._est._S_asset                      # fast timescale, at stress end
    assert S_a[0, :6].mean() > S_a[0, 6:].mean()


def test_lazy_n_and_mask():
    rng = np.random.default_rng(0)
    sk = SqueezeKernel()
    r = rng.normal(0, 0.01, 8)
    sk.update(r, mask=np.ones(8, bool))
    assert sk.state()["n_assets"] == 8
    m = np.ones(8, bool)
    m[2] = False
    sk.update(r, mask=m)
    cov = sk.covariance()
    assert cov.shape == (8, 8) and np.isfinite(cov).all()


def test_psd_along_path():
    rng = np.random.default_rng(1)
    sk = SqueezeKernel()
    for t, r in enumerate(rng.standard_t(5, size=(400, 15)) * 0.01):
        if t % 7 == 0:
            r[t % 15] = np.nan
        sk.update(r)
        if t % 50 == 49:
            assert np.linalg.eigvalsh(sk.covariance()).min() > -1e-10


def test_state_diagnostics():
    rng = np.random.default_rng(2)
    sk = SqueezeKernel()
    for r in rng.normal(0, 0.01, size=(120, 10)):
        sk.update(r)
    st = sk.state()
    assert st["t"] == 120 and st["n_assets"] == 10
    assert len(st["rung_nu"]) == 3 and st["rung_nu"][0] > 1
    assert 0.0 < st["kappa_t"] < 2.0
    assert st["omega_t"] > 0.0


